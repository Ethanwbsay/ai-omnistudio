import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:question_solver/models/image_api_profile.dart';
import 'package:question_solver/services/image_api_service.dart';
import 'package:question_solver/services/image_store.dart';
import 'package:question_solver/services/image_studio_controller.dart';
import 'package:question_solver/widgets/image_mask_editor.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'image_api_service_test.dart' show imageProfile, ImageStreamingClient;

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  late Directory directory;
  late ImageStore store;

  setUp(() async {
    SharedPreferences.setMockInitialValues({});
    directory = await Directory.systemTemp.createTemp('image-studio-test-');
    store = ImageStore(directory: directory);
  });

  tearDown(() async {
    expect(directory.absolute.path,
        startsWith(Directory.systemTemp.absolute.path));
    expect(directory.path.split(Platform.pathSeparator).last,
        startsWith('image-studio-test-'));
    await directory.delete(recursive: true);
  });

  test(
      'mask keeps source dimensions and clears alpha only in the painted region',
      () async {
    final bytes = await renderImageMask(80, 40, [
      MaskStroke(width: .2, points: [const Offset(.5, .5)])
    ]);
    final codec = await ui.instantiateImageCodec(bytes);
    final image = (await codec.getNextFrame()).image;
    expect([image.width, image.height], [80, 40]);
    final rgba = (await image.toByteData(format: ui.ImageByteFormat.rawRgba))!
        .buffer
        .asUint8List();
    expect(rgba[(20 * 80 + 40) * 4 + 3], 0);
    expect(rgba[3], 255);
    image.dispose();
    codec.dispose();
  });

  test('image configuration and gallery survive reopening and deletion',
      () async {
    await store.saveProfiles([imageProfile]);
    expect((await store.loadProfiles()).single.toJson(), imageProfile.toJson());
    final bytes = await renderImageMask(8, 8, []);
    final artifact = await store.persist(
        bytes: bytes,
        prompt: 'test',
        model: 'image-model',
        mode: ImageTaskMode.textToImage);
    await store.saveHistory([artifact]);
    final reopened = ImageStore(directory: directory);
    final history = await reopened.loadHistory();
    expect(history.single.toJson(), artifact.toJson());
    expect(await File(history.single.path).readAsBytes(), bytes);
    await reopened.saveHistory([]);
    await reopened.deleteFile(artifact);
    expect(await reopened.loadHistory(), isEmpty);
    expect(await File(artifact.path).exists(), isFalse);
  });

  test('controller persists generated bytes and rejects non-image API output',
      () async {
    final png = await renderImageMask(16, 16, []);
    var valid = true;
    final controller = ImageStudioController(
        store: store,
        service: ImageApiService(
            clientFactory: () => MockClient((_) async => http.Response(
                jsonEncode({
                  'data': [
                    {
                      'b64_json': base64Encode(valid ? png : [1, 2, 3])
                    }
                  ]
                }),
                200))));
    await controller.load();
    await controller.generate(
        profile: imageProfile,
        mode: ImageTaskMode.textToImage,
        prompt: 'landscape',
        size: '',
        quality: '',
        count: 1);
    expect(controller.error, isNull);
    expect(controller.busy, isFalse);
    expect((await store.loadHistory()).single.prompt, 'landscape');
    valid = false;
    await controller.generate(
        profile: imageProfile,
        mode: ImageTaskMode.textToImage,
        prompt: 'invalid',
        size: '',
        quality: '',
        count: 1);
    expect(controller.error, isNotNull);
    expect(controller.history, hasLength(1));
    controller.dispose();
  });

  test(
      'heartbeats followed by final SSE image reach the persisted gallery with one POST',
      () async {
    final png = await renderImageMask(16, 16, []);
    var posts = 0;
    final streamingProfile = ImageApiProfile.fromJson(
        {...imageProfile.toJson(), 'responseMode': 'stream'});
    final controller = ImageStudioController(
        store: store,
        service: ImageApiService(
            clientFactory: () => MockClient((request) async {
                  posts++;
                  expect(request.method, 'POST');
                  return http.Response(
                      'data:\n\nevent: ping\ndata: waiting\n\n'
                      'event: image_edit.completed\ndata: ${jsonEncode({
                            'b64_json': base64Encode(png)
                          })}\n\n',
                      200,
                      headers: {'content-type': 'text/event-stream'});
                })));
    await controller.load();
    await controller.generate(
        profile: streamingProfile,
        mode: ImageTaskMode.edit,
        prompt: 'original prompt',
        size: '',
        quality: '',
        count: 1,
        images: [png]);
    expect(controller.error, isNull);
    expect(controller.history, hasLength(1));
    final reopened = await store.loadHistory();
    expect(reopened.single.prompt, 'original prompt');
    expect(await File(reopened.single.path).readAsBytes(), png);
    expect(posts, 1);
    controller.dispose();
  });

  test(
      'multi-megabyte folded final SSE image decodes, saves and reopens intact',
      () async {
    const width = 960, height = 720;
    final rgba = Uint8List(width * height * 4);
    var noise = 123456789;
    for (var i = 0; i < rgba.length; i += 4) {
      for (var channel = 0; channel < 3; channel++) {
        noise ^= noise << 13;
        noise ^= noise >> 17;
        noise ^= noise << 5;
        noise &= 0xffffffff;
        rgba[i + channel] = noise & 255;
      }
      rgba[i + 3] = 255;
    }
    final buffer = await ui.ImmutableBuffer.fromUint8List(rgba);
    final descriptor = ui.ImageDescriptor.raw(buffer,
        width: width, height: height, pixelFormat: ui.PixelFormat.rgba8888);
    final codec = await descriptor.instantiateCodec();
    final rendered = (await codec.getNextFrame()).image;
    final png = (await rendered.toByteData(format: ui.ImageByteFormat.png))!
        .buffer
        .asUint8List();
    rendered.dispose();
    codec.dispose();
    descriptor.dispose();
    buffer.dispose();
    final json = jsonEncode(
        {'type': 'image_edit.completed', 'b64_json': base64Encode(png)});
    expect(json.length, greaterThan(2587972));
    final pieces = <String>[];
    for (var i = 0; i < json.length; i += 8192) {
      pieces.add(json.substring(i, (i + 8192).clamp(0, json.length)));
    }
    final responseBytes = utf8.encode('event: image_edit.completed\n'
        '${pieces.map((p) => 'data: $p').join('\n')}');
    var posts = 0;
    final profile = ImageApiProfile.fromJson(
        {...imageProfile.toJson(), 'responseMode': 'stream'});
    final controller = ImageStudioController(
        store: store,
        service: ImageApiService(
            clientFactory: () => ImageStreamingClient((request) async {
                  posts++;
                  return http.StreamedResponse(
                      Stream.fromIterable([
                        for (var i = 0; i < responseBytes.length; i += 16384)
                          responseBytes.sublist(
                              i, (i + 16384).clamp(0, responseBytes.length))
                      ]),
                      200,
                      headers: {'content-type': 'text/event-stream'});
                })));
    try {
      await controller.load();
      await controller.generate(
          profile: profile,
          mode: ImageTaskMode.edit,
          prompt: 'large image',
          size: '',
          quality: '',
          count: 1,
          images: [await renderImageMask(16, 16, [])]);
      expect(controller.error, isNull);
      expect(controller.history, hasLength(1));
      final reopened = await store.loadHistory();
      final saved = await File(reopened.single.path).readAsBytes();
      expect(saved, png);
      final savedCodec = await ui.instantiateImageCodec(saved);
      final savedImage = (await savedCodec.getNextFrame()).image;
      expect([savedImage.width, savedImage.height], [width, height]);
      savedImage.dispose();
      savedCodec.dispose();
      expect(posts, 1);
    } finally {
      controller.dispose();
    }
  });

  test('retry downloads keeps original metadata and never resubmits generation',
      () async {
    final png = await renderImageMask(16, 16, []);
    var posts = 0, gets = 0;
    final controller = ImageStudioController(
        store: store,
        service: ImageApiService(
            clientFactory: () => MockClient((request) async {
                  if (request.method == 'POST') {
                    posts++;
                    return http.Response(
                        jsonEncode({
                          'data': [
                            {'b64_json': base64Encode(png)},
                            {'url': 'https://cdn.test/second.png'},
                          ]
                        }),
                        200);
                  }
                  return ++gets == 1
                      ? http.Response('offline', 503)
                      : http.Response.bytes(png, 200);
                })));
    await controller.load();
    await controller.generate(
        profile: imageProfile,
        mode: ImageTaskMode.imageToImage,
        prompt: 'original prompt',
        size: '',
        quality: '',
        count: 2,
        images: [png]);
    expect(controller.canRetryDownload, isTrue);
    expect(controller.history, hasLength(1));
    expect(controller.error, contains('生成成功'));
    await controller.generate(
        profile: imageProfile,
        mode: ImageTaskMode.textToImage,
        prompt: 'should not submit',
        size: '',
        quality: '',
        count: 1);
    expect(posts, 1);
    await controller.retryPendingDownload();
    expect(controller.canRetryDownload, isFalse);
    expect(controller.error, isNull);
    expect(controller.busy, isFalse);
    expect(controller.history, hasLength(2));
    expect(controller.history.first.prompt, 'original prompt');
    expect(controller.history.first.mode, '图生图');
    expect(posts, 1);
    expect(gets, 2);
    controller.dispose();
  });
}
